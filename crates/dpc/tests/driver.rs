//! Integration tests: run the `dpc` binary.

use std::path::PathBuf;
use std::process::Command;

fn dpc() -> Command {
    Command::new(env!("CARGO_BIN_EXE_dpc"))
}

/// A fresh scratch directory under the cargo target dir.
fn scratch(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn compiles_tiny_module() {
    let dir = scratch("compiles_tiny_module");
    let src = dir.join("tiny.pas");
    std::fs::write(&src, "module tiny;\n").unwrap();
    let out = dir.join("out.s");
    let st = dpc()
        .arg("-I")
        .arg(&dir)
        .arg("-o")
        .arg(&out)
        .arg(&src)
        .status()
        .unwrap();
    assert!(st.success());
    let asm = std::fs::read_to_string(&out).unwrap();
    assert!(asm.starts_with("| generated by dpc"), "{asm}");
}

#[test]
fn default_output_name() {
    let dir = scratch("default_output_name");
    let src = dir.join("m.pas");
    std::fs::write(&src, "module m;\n").unwrap();
    assert!(dpc().arg(&src).status().unwrap().success());
    assert!(dir.join("m.s").exists());
}

#[test]
fn missing_input_is_an_error() {
    let dir = scratch("missing_input_is_an_error");
    let out = dpc().arg(dir.join("nope.pas")).output().unwrap();
    assert_eq!(out.status.code(), Some(1));
    let err = String::from_utf8(out.stderr).unwrap();
    assert!(err.starts_with("dpc: error: cannot read"), "{err}");
}

#[test]
fn usage_error() {
    let out = dpc().output().unwrap();
    assert_eq!(out.status.code(), Some(2));
    assert!(String::from_utf8(out.stderr)
        .unwrap()
        .contains("usage: dpc"));
}

#[test]
fn help_is_not_an_error() {
    let out = dpc().arg("--help").output().unwrap();
    assert_eq!(out.status.code(), Some(0));
    assert!(String::from_utf8(out.stdout)
        .unwrap()
        .contains("usage: dpc"));
}

#[test]
fn refuses_to_overwrite_input() {
    let dir = scratch("refuses_to_overwrite_input");
    let src = dir.join("m.s");
    std::fs::write(&src, "module m;\n").unwrap();
    let out = dpc().arg(&src).output().unwrap();
    assert_eq!(out.status.code(), Some(1));
    assert_eq!(std::fs::read_to_string(&src).unwrap(), "module m;\n");
}

#[test]
fn check_only_accepts_tst_lock() {
    let dir = scratch("check_only_accepts_tst_lock");
    let src = dir.join("tst.pas");
    std::fs::write(
        &src,
        "module proc1_tst;
type
  proc1_$pcb_t = record
    pad: array[1..16] of integer32;
    resource_locks_held: set of 0..31;
  end;
var
  proc1_$current_pcb: extern ^proc1_$pcb_t;
function proc1_$tst_lock(lock_id: integer): boolean; options(val_param);
begin
  proc1_$tst_lock := lock_id in proc1_$current_pcb^.resource_locks_held;
end;
",
    )
    .unwrap();
    let out = dpc().arg("--check-only").arg(&src).output().unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(!dir.join("tst.s").exists());
}

#[test]
fn semantic_errors_have_positions() {
    let dir = scratch("semantic_errors_have_positions");
    let src = dir.join("bad.pas");
    std::fs::write(
        &src,
        "module bad;\nprocedure p;\nbegin\n  nosuch := 1;\nend;\n",
    )
    .unwrap();
    let out = dpc().arg(&src).output().unwrap();
    assert_eq!(out.status.code(), Some(1));
    let err = String::from_utf8(out.stderr).unwrap();
    assert!(
        err.contains("bad.pas:4:3: error: undefined identifier `nosuch`"),
        "{err}"
    );
}

#[test]
fn compiles_tst_lock() {
    let dir = scratch("compiles_tst_lock");
    let src = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/conformance/proc1_tst_lock.pas");
    let out = dir.join("tst.s");
    let run = dpc().arg("-o").arg(&out).arg(&src).output().unwrap();
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let asm = std::fs::read_to_string(&out).unwrap();
    assert!(asm.contains("\t.globl\tPROC1_$TST_LOCK\n"), "{asm}");
    assert!(asm.contains("\tbtst\t%d0,%d1\n"), "{asm}");
}

#[test]
fn unsupported_constructs_are_diagnosed_not_compiled() {
    let dir = scratch("unsupported_constructs_are_diagnosed_not_compiled");
    let src = dir.join("u.pas");
    std::fs::write(
        &src,
        "module u;\nprocedure p(var x: integer);\nbegin\n  case x of 1: x := 2; end;\nend;\n",
    )
    .unwrap();
    let out = dpc().arg(&src).output().unwrap();
    assert_eq!(out.status.code(), Some(1));
    let err = String::from_utf8(out.stderr).unwrap();
    assert!(
        err.contains("u.pas:4:3: error: this statement is not supported yet"),
        "{err}"
    );
    assert!(!dir.join("u.s").exists());
}

#[test]
fn fragment_origin_shifts_and_drops_end_padding() {
    let dir = scratch("fragment_origin_shifts_and_drops_end_padding");
    let src = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/conformance/proc1_tst_lock.pas");
    let out = dir.join("tst.s");
    let run = dpc()
        .arg("--fragment-origin")
        .arg("0xE148CA")
        .arg("-o")
        .arg(&out)
        .arg(&src)
        .output()
        .unwrap();
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let asm = std::fs::read_to_string(&out).unwrap();
    assert!(
        asm.contains("\t.set\t__dpc_fragment_origin,0xe148ca\n"),
        "{asm}"
    );
    assert!(asm.contains("\t.text\n\t.space\t2\t|"), "{asm}");
    assert!(!asm.contains(".balignw"), "{asm}");
}
