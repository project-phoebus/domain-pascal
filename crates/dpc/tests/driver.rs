/// The routine `name`'s text in `asm`.
fn routine<'a>(asm: &'a str, name: &str) -> &'a str {
    let start = asm.find(&format!("\n{name}:\n")).unwrap();
    let end = asm[start..].find("\trts\n").unwrap();
    &asm[start..start + end]
}

#[test]
