//! Integration tests: run the `dpc` binary.

use std::path::PathBuf;
use std::process::Command;

fn dpc() -> Command {
    Command::new(env!("CARGO_BIN_EXE_dpc"))
}

/// A fresh scratch directory under the cargo target dir.
fn scratch(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn compiles_tiny_module() {
    let dir = scratch("compiles_tiny_module");
    let src = dir.join("tiny.pas");
    std::fs::write(&src, "module tiny;\n").unwrap();
    let out = dir.join("out.s");
    let st = dpc()
        .arg("-I")
        .arg(&dir)
        .arg("-o")
        .arg(&out)
        .arg(&src)
        .status()
        .unwrap();
    assert!(st.success());
    let asm = std::fs::read_to_string(&out).unwrap();
    assert!(asm.starts_with("| generated by dpc"), "{asm}");
}

