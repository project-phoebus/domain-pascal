/// Compile `src` (written to a scratch file) with `opts`; the output
/// text, or the exit code and stderr.
fn compile_with(name: &str, src: &str, opts: &[&str]) -> Result<String, (Option<i32>, String)> {
    let dir = scratch(name);
    let path = dir.join("m.pas");
    std::fs::write(&path, src).unwrap();
    let out = dir.join("m.s");
    // `--strict`: these tests pin the image's forms and the refusals
    // (bead domain-pascal-5kgg; `compile_default` for the default mode).
    let run = dpc()
        .arg("--strict")
        .args(opts)
        .arg("-o")
        .arg(&out)
        .arg(&path)
        .output()
        .unwrap();
    if run.status.success() {
        Ok(std::fs::read_to_string(&out).unwrap())
    } else {
        Err((
            run.status.code(),
            String::from_utf8_lossy(&run.stderr).into_owned(),
        ))
    }
}

/// Two routines with a `for` fill loop each (codegen-patterns 7).
const TWO_FILLS: &str = "module m;
var
  a: extern array[0..255] of integer32;
procedure m_$first;
var i: integer;
begin
  for i := 0 to 255 do a[i] := 0;
end;
procedure m_$second;
var i: integer;
begin
  for i := 0 to 255 do a[i] := 0;
end;
";

const FILLER: &str = "\t.balignw\t4,0x2048";
const ZERO_PAD: &str = "\t.balignw\t4,0x0000";

#[test]
fn loop_align_on_by_default() {
    let asm = compile_with("loop_align_on_by_default", TWO_FILLS, &[]).unwrap();
    // two loop heads and the module end
    assert_eq!(asm.matches(FILLER).count(), 3, "{asm}");
    assert!(!asm.contains(ZERO_PAD), "{asm}");
    let on = compile_with("loop_align_on", TWO_FILLS, &["--loop-align=on"]).unwrap();
    // the same code (the header line names the source file)
    assert_eq!(
        asm.split_once('\n').unwrap().1,
        on.split_once('\n').unwrap().1
    );
}

#[test]
fn loop_align_off() {
    let asm = compile_with("loop_align_off", TWO_FILLS, &["--loop-align=off"]).unwrap();
    assert!(!asm.contains("0x2048"), "{asm}");
    assert!(
        asm.trim_end()
            .ends_with("rts\n\t.balignw\t4,0x0000\t| zero words: the last routine does not align"),
        "{asm}"
    );
}

#[test]
fn loop_align_off_from_a_routine() {
    // the Pascal name in any case, or the external symbol
    for name in ["m_$second", "M_$SECOND", "M_$Second"] {
        let asm = compile_with(
            "loop_align_off_from_a_routine",
            TWO_FILLS,
            &[&format!("--loop-align-off-from={name}")],
        )
        .unwrap();
        let (first, second) = asm.split_once("M_$SECOND:").unwrap();
        assert_eq!(first.matches(FILLER).count(), 1, "{asm}");
        assert!(!second.contains("0x2048"), "{asm}");
        assert!(second.contains(ZERO_PAD), "{asm}");
    }
    // a fragment that ends its module whose last routine aligns
    let asm = compile_with(
        "loop_align_off_from_a_routine",
        TWO_FILLS,
        &[
            "--fragment-origin",
            "0x1000",
            "--fragment-ends-module",
            "--loop-align-off-from=m_$first",
        ],
    )
    .unwrap();
    assert!(!asm.contains("0x2048"), "{asm}");
    assert!(asm.contains(ZERO_PAD), "{asm}");
}

/// codegen-patterns 13, "Stores of constants" (bead domain-pascal-53xi):
/// a longword constant in `moveq`'s range below the next statement's zero
/// word or longword is `move.l #n` (MAC_OS_$INIT 0xE2F55E, 0xE311C8); the
/// shapes the image does not settle are refused: another constant above
/// it (a byte, a nonzero one, the same value in a word), a different
/// constant just below it in the previous statement, its value used
/// again by a later statement's expression (NETWORK_$INIT 0xE2F782 keeps
/// the `moveq` register for `ec + 1`), and a `moveq` in the statement
/// right after a run of constant stores (NETWORK_$INIT 0xE2F7D6 takes
/// another register).  A `device` longword is `move.l #n`, never refused.
#[test]
fn small_long_constant_runs_refused() {
    let src = |body: &str| {
        format!(
            "module m;
type
  rb = record l: integer32; b: char; end;
  rw = record l: integer32; w: integer; pad: integer; m: integer32; end;
var
  xb: rb;
  xw: rw;
  e: integer32;
  dv: [device] rw;
procedure m_$p;
begin
{body}
end;
"
        )
    };
    let refused = [
        (
            "small_long_below_byte",
            "  xb.l := 7;\n  xb.b := chr(0);",
            "m.pas:12:3: error: a longword constant in `moveq`'s range stored just below the \
             next statement's constant other than a zero word or longword or the same longword",
        ),
        (
            "small_long_below_nonzero",
            "  xw.l := 7;\n  xw.w := 3;",
            "just below the next statement's constant other than a zero",
        ),
        (
            "small_long_below_same_word",
            "  xw.l := 1;\n  xw.w := 1;",
            "just below the next statement's constant other than a zero",
        ),
        (
            "small_long_above_other",
            "  xw.pad := 0;\n  xw.m := 5;",
            "m.pas:13:3: error: a longword constant in `moveq`'s range stored just above the \
             previous statement's other constant",
        ),
        (
            "small_long_used_again",
            "  xw.l := 1;\n  xw.m := e + 1;",
            "its value used again by a later statement's expression",
        ),
        (
            "small_long_after_run",
            "  xw.l := 1;\n  e := 1;\n  xw.m := e + 60;",
            "m.pas:14:3: error: a constant loaded with `moveq` right after a run of constant \
             stores from registers",
        ),
    ];
    for (name, body, msg) in refused {
        let (code, err) = compile_with(name, &src(body), &[]).unwrap_err();
        assert_eq!(code, Some(1), "{name}");
        assert!(err.contains(msg), "{name}: {err}");
    }
    // A zero word above: `move.l #1` (MAC_OS_$INIT 0xE2F55E).
    let asm = compile_with(
        "small_long_below_word",
        &src("  xw.l := 1;\n  xw.w := 0;"),
        &[],
    )
    .unwrap();
    assert!(
        asm.contains("\tmove.l\t#1,(8,%a5)\n\tclr.w\t(0xc,%a5)\n"),
        "{asm}"
    );
    // A device record: `move.l #n`, whatever is next to it.
    let asm = compile_with(
        "small_long_device",
        &src("  dv.l := 1;\n  dv.w := 1;\n  e := e + 1;"),
        &[],
    )
    .unwrap();
    assert!(asm.contains("\tmove.l\t#1,"), "{asm}");
}

