//! Assembly emitter: gas syntax for `m68k-elf-as` (CLAUDE.md 4.4).
//!
//! Stub: emits only a comment header.

use dpc_ir::Module;

/// Render `module` as assembly text.  `source_name` is recorded in the
/// header comment.
pub fn emit(_module: &Module, source_name: &str) -> String {
    format!("| generated by dpc from {source_name}\n")
}

#[cfg(test)]
mod tests {
    #[test]
    fn emits_header() {
        let s = super::emit(&dpc_ir::Module::default(), "x.pas");
        assert_eq!(s, "| generated by dpc from x.pas\n");
    }
}
