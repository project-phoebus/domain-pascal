        sub.l   %d2, %d1                /* 00e0ad46 */
        addq.w  #1, %d0                 /* 00e0ad48  quotient bit */
3:      dbf     %d3, 2b                 /* 00e0ad4a */
        movem.l (%sp)+, %d1-%d3         /* 00e0ad4e */
        rts                             /* 00e0ad52 */

