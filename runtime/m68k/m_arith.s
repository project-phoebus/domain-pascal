        rts                             /* 00e0ad0a */

/*
 * M$DIU$LLL (0x00E0AD0C) - unsigned 32 / 32.  A divisor below 0x10000 takes
 * the two-divu path; otherwise a 32-step shift-and-subtract with the
 * remainder in D1 and the quotient bits shifted into D0.
 */
M$DIU$LLL:
        tst.w   (0x8,%sp)               /* 00e0ad0c  hi(b) */
        bne.s   1f                      /* 00e0ad10 */
        moveq   #0, %d0                 /* 00e0ad12 */
        move.w  (0x4,%sp), %d0          /* 00e0ad14  hi(a) */
        divu.w  (0xa,%sp), %d0          /* 00e0ad18  rem1:q1 */
        movea.l %d0, %a0                /* 00e0ad1c */
        move.w  (0x6,%sp), %d0          /* 00e0ad1e  rem1:lo(a) */
        divu.w  (0xa,%sp), %d0          /* 00e0ad22  rem2:q2 */
        swap    %d0                     /* 00e0ad26 */
        move.w  %a0, %d0                /* 00e0ad28 */
        swap    %d0                     /* 00e0ad2a  q1:q2 */
        rts                             /* 00e0ad2c */
1:      movem.l %d1-%d3, -(%sp)         /* 00e0ad2e */
        clr.l   %d1                     /* 00e0ad32  remainder */
        move.l  (0x10,%sp), %d0         /* 00e0ad34  a */
        move.l  (0x14,%sp), %d2         /* 00e0ad38  b */
        moveq   #0x1f, %d3              /* 00e0ad3c  32 steps */
2:      lsl.l   #1, %d0                 /* 00e0ad3e */
        roxl.l  #1, %d1                 /* 00e0ad40 */
        cmp.l   %d2, %d1                /* 00e0ad42 */
