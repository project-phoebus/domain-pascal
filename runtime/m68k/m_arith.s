/*
 * math/sau2/arith.s - M$ARITH, the Domain Pascal compiler's arithmetic
 * run-time routines (m68k / SAU2)
 *
 * Generated by: Claude Opus 5.5 (source-w99n, 2026-10-11)
 *
 * SAU2 map: `I E0ABD4 M$ARITH size = 1DC' (0xE0ABD4 .. 0xE0ADB0), twelve
 * entry points, transcribed instruction for instruction from the image
 * (`gsk analyze' / `gsk read' 0xE0ABD4 0x1DC, disassembled with
 * m68k-elf-objdump).  This is hand-written assembly, not compiled Pascal:
 * no link frame, the arguments are read straight off the caller's stack at
 * the Domain Pascal offsets, the result is returned in D0, and only D0, D1
 * and A0 are free (the routines that need D1..D3 save them with movem).
 *
 * Pascal frames (a word argument is a 2-byte slot; C callers pack it with
 * the macros in math/math.h, arch/arch.h "Pascal parameter slots"):
 *
 *   M$MIS$LLL  (4) a.l (8) b.l       signed   a * b, low 32 bits
 *   M$MIU$LLW  (4) a.l (8) b.w       unsigned a * b, low 32 bits
 *   M$MIU$LLL  (4) a.l (8) b.l       unsigned a * b, low 32 bits
 *   M$MIS$LLW  (4) a.l (8) b.w       signed   a * b, low 32 bits
 *   M$DIU$LLW  (4) a.l (8) b.w       unsigned a div b
 *   M$DIS$LLW  (4) a.l (8) b.w       signed   a div b
 *   M$OIU$WLW  (4) a.l (8) b.w       unsigned a mod b  (word result)
 *   M$DIS$LLL  (4) a.l (8) b.l       signed   a div b
 *   M$DIU$LLL  (4) a.l (8) b.l       unsigned a div b
 *   M$OIS$WLW  (4) a.l (8) b.w       signed   a mod b  (word result)
 *   M$OIS$WWL  (4) a.w (6) b.l       signed   a mod b  (word result)
 *   M$OIS$LLL  (4) a.l (8) b.l       signed   a mod b  (= M$OIU$LLL)
 *
 * The portable models (the host build) are math/mult.c, div.c and mod.c.
 *
 * Notes:
 *   - M$DIS$LLW writes its divisor argument: `eor.w D1w,(0x10,SP)' leaves
 *     divisor XOR high(dividend) in the caller's (by-value) slot.
 *   - M$OIS$LLL takes the result's sign from the dividend's high WORD
 *     (`tst.w (0x10,SP)'), M$DIS$LLW its quotient's sign from the XOR of
 *     the two high words: both are the sign bits.
 *   - The shift-subtract loops keep a 32-bit remainder that never carries
 *     out of bit 31: a divisor below 2^31 keeps it below 2^31, and one of
 *     2^31 or more is first reached at the 32nd (last) step.
 *   - Division by zero takes the divu zero-divide trap (vector 5) on the
 *     word paths; the M$DIU$LLL loop path cannot see a zero divisor.
 */

        .section ".text.M$ARITH","ax",@progbits
        .balign 2

        .global M$MIS$LLL
        .global M$MIU$LLW
        .global M$MIU$LLL
        .global M$MIS$LLW
        .global M$DIU$LLW
        .global M$DIS$LLW
        .global M$OIU$WLW
        .global M$DIS$LLL
        .global M$DIU$LLL
        .global M$OIS$WLW
        .global M$OIS$WWL
        .global M$OIS$LLL
        .global M$OIU$LLL

/*
 * M$MIS$LLL (0x00E0ABD4) - signed 32 x 32.  A sign word is pushed, each
 * negative operand is pushed negated and flips it, M$MIU$LLL multiplies
 * the magnitudes ((4) = b, (8) = a), the product is negated if the sign
 * word ends up set.
 */
M$MIS$LLL:
        clr.w   -(%sp)                  /* 00e0abd4  sign word = 0 */
        move.l  (0x6,%sp), -(%sp)       /* 00e0abd6  push a */
        bge.w   1f                      /* 00e0abda */
        not.w   (0x4,%sp)               /* 00e0abde  flip sign */
        neg.l   (%sp)                   /* 00e0abe2  |a| */
1:      move.l  (0xe,%sp), -(%sp)       /* 00e0abe4  push b */
        bge.w   2f                      /* 00e0abe8 */
        not.w   (0x8,%sp)               /* 00e0abec  flip sign */
        neg.l   (%sp)                   /* 00e0abf0  |b| */
2:      bsr.w   M$MIU$LLL               /* 00e0abf2 */
        addq.w  #8, %sp                 /* 00e0abf6 */
        tst.w   (%sp)+                  /* 00e0abf8  sign word */
        bge.w   3f                      /* 00e0abfa */
        neg.l   %d0                     /* 00e0abfe */
3:      rts                             /* 00e0ac00 */

/*
 * M$MIU$LLW (0x00E0AC02) - unsigned 32 x 16: (hi(a) * b) << 16 + lo(a) * b.
 */
M$MIU$LLW:
        move.w  (0x4,%sp), %d0          /* 00e0ac02  hi(a) */
        mulu.w  (0x8,%sp), %d0          /* 00e0ac06  * b */
        swap    %d0                     /* 00e0ac0a */
        clr.w   %d0                     /* 00e0ac0c  << 16 */
        movea.l %d0, %a0                /* 00e0ac0e */
        move.w  (0x6,%sp), %d0          /* 00e0ac10  lo(a) */
        mulu.w  (0x8,%sp), %d0          /* 00e0ac14  * b */
        add.l   %a0, %d0                /* 00e0ac18 */
        rts                             /* 00e0ac1a */

/*
 * M$MIU$LLL (0x00E0AC1C) - unsigned 32 x 32, low 32 bits:
 * (hi(a) * lo(b)) << 16 + (hi(b) * lo(a)) << 16 + lo(a) * lo(b).
 */
M$MIU$LLL:
        move.w  (0x4,%sp), %d0          /* 00e0ac1c  hi(a) */
        mulu.w  (0xa,%sp), %d0          /* 00e0ac20  * lo(b) */
        swap    %d0                     /* 00e0ac24 */
        clr.w   %d0                     /* 00e0ac26 */
        movea.l %d0, %a0                /* 00e0ac28 */
        move.w  (0x8,%sp), %d0          /* 00e0ac2a  hi(b) */
        mulu.w  (0x6,%sp), %d0          /* 00e0ac2e  * lo(a) */
        swap    %d0                     /* 00e0ac32 */
        clr.w   %d0                     /* 00e0ac34 */
        adda.l  %d0, %a0                /* 00e0ac36 */
        move.w  (0x6,%sp), %d0          /* 00e0ac38  lo(a) */
        mulu.w  (0xa,%sp), %d0          /* 00e0ac3c  * lo(b) */
        add.l   %a0, %d0                /* 00e0ac40 */
        rts                             /* 00e0ac42 */

/*
 * M$MIS$LLW (0x00E0AC44) - signed 32 x 16: the high partial product is
 * signed (muls), corrected by lo(a) when b is negative; only its low word
 * survives the swap.
 */
M$MIS$LLW:
        move.w  (0x4,%sp), %d0          /* 00e0ac44  hi(a) */
        muls.w  (0x8,%sp), %d0          /* 00e0ac48  * b, signed */
        tst.w   (0x8,%sp)               /* 00e0ac4c */
        bpl.s   1f                      /* 00e0ac50 */
        sub.w   (0x6,%sp), %d0          /* 00e0ac52  b < 0: -= lo(a) */
1:      swap    %d0                     /* 00e0ac56 */
        clr.w   %d0                     /* 00e0ac58 */
        movea.l %d0, %a0                /* 00e0ac5a */
        move.w  (0x6,%sp), %d0          /* 00e0ac5c  lo(a) */
        mulu.w  (0x8,%sp), %d0          /* 00e0ac60  * (uint16)b */
        add.l   %a0, %d0                /* 00e0ac64 */
        rts                             /* 00e0ac66 */

/*
 * M$DIU$LLW (0x00E0AC68) - unsigned 32 / 16 in two divu.w steps: hi(a) / b
 * (q1, rem1), then rem1:lo(a) / b (q2); D0 = q1:q2.  Neither step can
 * overflow.
 */
M$DIU$LLW:
        moveq   #0, %d0                 /* 00e0ac68 */
        move.w  (0x4,%sp), %d0          /* 00e0ac6a  hi(a) */
        divu.w  (0x8,%sp), %d0          /* 00e0ac6e  rem1:q1 */
        movea.l %d0, %a0                /* 00e0ac72 */
        move.w  (0x6,%sp), %d0          /* 00e0ac74  rem1:lo(a) */
        divu.w  (0x8,%sp), %d0          /* 00e0ac78  rem2:q2 */
        swap    %d0                     /* 00e0ac7c */
        move.w  %a0, %d0                /* 00e0ac7e  q1 */
        swap    %d0                     /* 00e0ac80  q1:q2 */
        rts                             /* 00e0ac82 */

/*
 * M$DIS$LLW (0x00E0AC84) - signed 32 / 16: M$DIU$LLW on the magnitudes,
 * negated when the operands' sign bits differ.  The sign test XORs into
 * the caller's divisor slot.
 */
M$DIS$LLW:
        movem.l %d1-%d2, -(%sp)         /* 00e0ac84 */
        move.l  (0xc,%sp), %d1          /* 00e0ac88  a */
        bpl.s   1f                      /* 00e0ac8c */
        neg.l   %d1                     /* 00e0ac8e  |a| */
1:      move.w  (0x10,%sp), %d2         /* 00e0ac90  b */
        bpl.s   2f                      /* 00e0ac94 */
        neg.w   %d2                     /* 00e0ac96  |b| */
2:      move.l  %d1, %d0                /* 00e0ac98 */
        move.w  #0, %d0                 /* 00e0ac9a */
        swap    %d0                     /* 00e0ac9e  0:hi|a| */
        divu.w  %d2, %d0                /* 00e0aca0  rem1:q1 */
        movea.l %d0, %a0                /* 00e0aca2 */
        move.w  %d1, %d0                /* 00e0aca4  rem1:lo|a| */
        divu.w  %d2, %d0                /* 00e0aca6  rem2:q2 */
        swap    %d0                     /* 00e0aca8 */
        move.w  %a0, %d0                /* 00e0acaa */
        swap    %d0                     /* 00e0acac  q1:q2 */
        move.w  (0xc,%sp), %d1          /* 00e0acae  hi(a) */
        eor.w   %d1, (0x10,%sp)         /* 00e0acb2  b ^= hi(a) (in place) */
        bpl.s   3f                      /* 00e0acb6 */
        neg.l   %d0                     /* 00e0acb8 */
3:      movem.l (%sp)+, %d1-%d2         /* 00e0acba */
        rts                             /* 00e0acbe */

/*
 * M$OIU$WLW (0x00E0ACC0) - unsigned 32 mod 16: the M$DIU$LLW steps, the
 * second divu's remainder swapped into D0w.
 */
M$OIU$WLW:
        moveq   #0, %d0                 /* 00e0acc0 */
        move.w  (0x4,%sp), %d0          /* 00e0acc2  hi(a) */
        divu.w  (0x8,%sp), %d0          /* 00e0acc6  rem1:q1 */
        movea.l %d0, %a0                /* 00e0acca  (A0 is not read again) */
        move.w  (0x6,%sp), %d0          /* 00e0accc  rem1:lo(a) */
        divu.w  (0x8,%sp), %d0          /* 00e0acd0  rem2:q2 */
        swap    %d0                     /* 00e0acd4  D0w = rem2 */
        rts                             /* 00e0acd6 */

/*
 * M$DIS$LLL (0x00E0ACD8) - signed 32 / 32: copies of the operands are
 * pushed (b, then a, so M$DIU$LLL sees (4) = a, (8) = b), each negative
 * one negated in place, the quotient negated if exactly one was.
 */
M$DIS$LLL:
        move.l  (0x8,%sp), -(%sp)       /* 00e0acd8  push b */
        bmi.s   2f                      /* 00e0acdc */
        move.l  (0x8,%sp), -(%sp)       /* 00e0acde  push a */
        bmi.s   4f                      /* 00e0ace2 */
        bsr.s   M$DIU$LLL               /* 00e0ace4  a >= 0, b >= 0 */
        addq.w  #8, %sp                 /* 00e0ace6 */
        rts                             /* 00e0ace8 */
2:      neg.l   (%sp)                   /* 00e0acea  |b| */
        move.l  (0x8,%sp), -(%sp)       /* 00e0acec  push a */
        bmi.s   3f                      /* 00e0acf0 */
        bsr.s   M$DIU$LLL               /* 00e0acf2  a >= 0, b < 0 */
        neg.l   %d0                     /* 00e0acf4 */
        addq.w  #8, %sp                 /* 00e0acf6 */
        rts                             /* 00e0acf8 */
3:      neg.l   (%sp)                   /* 00e0acfa  |a| */
        bsr.s   M$DIU$LLL               /* 00e0acfc  a < 0, b < 0 */
        addq.w  #8, %sp                 /* 00e0acfe */
        rts                             /* 00e0ad00 */
